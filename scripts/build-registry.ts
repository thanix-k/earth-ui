// Builds what's derived from registry.json, which is edited by hand:
//   app/earth.css   (the `base` item's CSS, for the docs app)
//   public/r/*      (via `shadcn build`, then validated)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const rel = (...p: string[]) => path.join(root, ...p);

type CssTree = { [key: string]: string | CssTree };
type Vars = Record<string, string>;
type BaseItem = {
  name: string;
  cssVars: { theme?: Vars; light: Vars; dark: Vars };
  css: CssTree;
};

// ── Docs CSS: the same CSS a consumer gets from `shadcn init @earth-ui/base` ──

function toCss(tree: CssTree, indent = ""): string {
  return Object.entries(tree)
    .map(([key, value]) => {
      if (typeof value === "string") return `${indent}${key}: ${value};`;
      if (key.startsWith("@") && Object.keys(value).length === 0) return `${indent}${key};`;
      return `${indent}${key} {\n${toCss(value, `${indent}  `)}\n${indent}}`;
    })
    .join("\n");
}

function writeDocsCss(base: BaseItem) {
  const { cssVars, css } = base;
  const vars = (v: Vars = {}) =>
    Object.fromEntries(Object.entries(v).map(([k, value]) => [`--${k}`, value]));
  // Only colours get a `--color-*` utility, as `shadcn add` does.
  const aliases = Object.fromEntries(
    Object.keys(cssVars.light)
      .filter((k) => !k.startsWith("radius"))
      .map((k) => [`--color-${k}`, `var(--${k})`]),
  );
  const tree: CssTree = {
    '@import "tailwindcss"': {},
    "@custom-variant dark (&:is(.dark *))": {},
    ...css,
    ":root": vars(cssVars.light),
    ".dark": vars(cssVars.dark),
    "@theme inline": {
      "--font-sans": "var(--font-inter)",
      ...vars(cssVars.theme),
      ...aliases,
    },
  };
  writeFileSync(
    rel("app/earth.css"),
    `/* Generated by scripts/build-registry.ts from registry.json. Do not edit. */\n${toCss(tree)}\n`,
  );
}

// ── shadcn build ─────────────────────────────────────────────────────────────

const shadcn = (...args: string[]) =>
  execFileSync(rel("node_modules/.bin/shadcn"), args, { cwd: root, stdio: "inherit" });

const registry = JSON.parse(readFileSync(rel("registry.json"), "utf8"));
const base = registry.items.find((i: { name: string }) => i.name === "base");
if (!base) throw new Error("registry.json: no `base` item");
writeDocsCss(base);

shadcn("build", "registry.json", "--output", "public/r");
shadcn("registry", "validate", "registry.json");
console.log(`✓ ${registry.items.length} items → public/r`);
